create or replace function public.get_production_monitoring(p_days integer default 7)
returns jsonb
language plpgsql
stable
security invoker
set search_path = ''
as $function$
declare
  v_days integer := least(greatest(coalesce(p_days, 7), 1), 45);
  v_result jsonb;
begin
  if not public.is_moderator() then
    raise exception 'insufficient_privilege' using errcode = '42501';
  end if;

  select jsonb_build_object(
    'generatedAt', now(),
    'summary', jsonb_build_object(
      'openAlerts', (select count(*) from public.production_alerts where status = 'open'),
      'criticalOpenAlerts', (select count(*) from public.production_alerts where status = 'open' and severity = 'critical'),
      'clientErrors24h', (select coalesce(sum(samples), 0) from public.production_event_daily where last_seen_at >= now() - interval '24 hours' and event_type in ('client_error', 'render_error', 'resource_error')),
      'apiFailures24h', (select coalesce(sum(samples), 0) from public.production_event_daily where last_seen_at >= now() - interval '24 hours' and event_type = 'api_error'),
      'slowPages24h', (select coalesce(sum(samples), 0) from public.production_event_daily where last_seen_at >= now() - interval '24 hours' and event_type = 'page_slow'),
      'slowApis24h', (select coalesce(sum(samples), 0) from public.production_event_daily where last_seen_at >= now() - interval '24 hours' and event_type = 'api_slow'),
      'latestEventAt', (select max(last_seen_at) from public.production_event_daily)
    ),
    'alerts', (
      select coalesce(jsonb_agg(to_jsonb(a) order by a.last_triggered_at desc), '[]'::jsonb)
      from (
        select id, fingerprint, event_type, severity, path, target, message,
               status_code, occurrences, status, first_triggered_at,
               last_triggered_at, resolved_at
        from public.production_alerts
        order by (status = 'open') desc, last_triggered_at desc
        limit 60
      ) a
    ),
    'events', (
      select coalesce(jsonb_agg(to_jsonb(e) order by e.last_seen_at desc), '[]'::jsonb)
      from (
        select day, fingerprint, event_type, severity, path, target, message,
               status_code, device_class, release, samples,
               case when duration_samples > 0 then round(total_duration_ms::numeric / duration_samples)::integer else null end as avg_duration_ms,
               max_duration_ms, first_seen_at, last_seen_at
        from public.production_event_daily
        where day >= (now() at time zone 'America/Sao_Paulo')::date - (v_days - 1)
        order by last_seen_at desc
        limit 120
      ) e
    )
  ) into v_result;

  return v_result;
end;
$function$;

revoke all on function public.get_production_monitoring(integer) from public, anon;
grant execute on function public.get_production_monitoring(integer) to authenticated;

create or replace function public.resolve_production_alert(p_alert_id bigint)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $function$
begin
  if not public.is_moderator() then
    raise exception 'insufficient_privilege' using errcode = '42501';
  end if;

  update public.production_alerts
  set status = 'resolved', resolved_at = now(), resolved_by = (select auth.uid())
  where id = p_alert_id and status = 'open';
  return found;
end;
$function$;

revoke all on function public.resolve_production_alert(bigint) from public, anon;
grant execute on function public.resolve_production_alert(bigint) to authenticated;

-- Reuse the existing once-per-day page-view maintenance path for retention.
create or replace function private.track_page_view_internal(p_path text)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_path text := left(coalesce(nullif(trim(p_path), ''), '/'), 120);
  v_day date := (now() at time zone 'America/Sao_Paulo')::date;
  v_first_view_today boolean;
begin
  if v_path !~ '^/' then v_path := '/' || v_path; end if;
  if v_path ~ '^/post/' then v_path := '/post/:id'; end if;
  if v_path ~ '^/perfil/' then v_path := '/perfil/:id'; end if;
  if v_path ~ '^/empresa/' then v_path := '/empresa/:id'; end if;

  if v_path not in (
    '/', '/mapa', '/estatisticas', '/empregos', '/mural', '/denuncias',
    '/perfil', '/perfil/:id', '/post/:id', '/empresa', '/empresa/:id',
    '/notificacoes', '/salvos', '/admin', '/privacidade', '/termos', '/login'
  ) then
    return;
  end if;

  select not exists (
    select 1 from public.site_analytics_daily where day = v_day
  ) into v_first_view_today;

  insert into public.site_analytics_daily(day, path, views)
  values (v_day, v_path, 1)
  on conflict (day, path) do update
    set views = public.site_analytics_daily.views + 1;

  if v_first_view_today then
    delete from public.client_error_logs where created_at < now() - interval '90 days';
    delete from public.production_event_daily where day < v_day - 44;
    delete from public.production_alerts
      where status = 'resolved' and resolved_at < now() - interval '180 days';
  end if;
end;
$function$;

